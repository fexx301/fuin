"""Write tee/src/pytables.rs: the Python 3.13 (Unicode 15.1) behaviour the sealed scorers rely on, generated, not hand-written.

str.isspace() characters, the zero of every decimal-digit (Nd) run, str.casefold() for every code point it changes, and the
sealed scorer pins (name, sha256 of the scorer file). Rerun if the reference Python or a scorer file changes.
"""
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from fuin import policy  # noqa: E402

ws = [c for c in range(0x110000) if chr(c).isspace()]
zeros = sorted({cp - unicodedata.decimal(chr(cp)) for cp in range(0x110000) if unicodedata.category(chr(cp)) == "Nd"})
fold = [(cp, chr(cp).casefold()) for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF and chr(cp).casefold() != chr(cp)]
esc = lambda s: "".join(f"\\u{{{ord(ch):x}}}" for ch in s)
out = ["// Generated by scripts/gen_tee_tables.py from Python " + sys.version.split()[0] + f" (Unicode {unicodedata.unidata_version}). Do not edit.",
       f"pub const PY_WS: [u32; {len(ws)}] = [{', '.join(hex(c) for c in ws)}];",
       f"pub const PY_DIGIT_ZEROS: [u32; {len(zeros)}] = [{', '.join(hex(z) for z in zeros)}];",
       f"pub const PY_CASEFOLD: [(u32, &str); {len(fold)}] = [", *[f'    ({hex(cp)}, "{esc(s)}"),' for cp, s in fold], "];",
       f"pub const SCORERS: [(&str, &str); {len(policy.SCORERS)}] = [{', '.join(f'(\"{n}\", \"{h}\")' for n, h in sorted(policy.SCORERS))}];", ""]
Path(__file__).resolve().parents[1].joinpath("tee/src/pytables.rs").write_text("\n".join(out))
print(f"whitespace {len(ws)}, digit runs {len(zeros)}, casefold {len(fold)}, scorers {sorted(n for n, _ in policy.SCORERS)}")
